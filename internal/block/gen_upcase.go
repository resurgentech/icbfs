//go:build ignore

// gen_upcase writes upcase_table.go: the simple-uppercase mapping of
// every UTF-16 code unit that has one, the same shape as NTFS's $UpCase
// table. It is generated once and committed, not regenerated on every
// Go upgrade: folded directories are sorted by this table, so it must
// never change under existing data (see Fold).
//
//	go run gen_upcase.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
)

func main() {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen_upcase.go from Unicode %s; DO NOT EDIT.\n\n", unicode.Version)
	fmt.Fprintf(&buf, "package block\n\n")
	fmt.Fprintf(&buf, "// upcasePairs maps a UTF-16 code unit to its simple uppercase. Pinned:\n")
	fmt.Fprintf(&buf, "// see gen_upcase.go.\n")
	fmt.Fprintf(&buf, "var upcasePairs = [...][2]uint16{\n")
	n := 0
	for r := rune(0); r <= 0xFFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		u := unicode.ToUpper(r)
		if u == r || u > 0xFFFF {
			continue
		}
		if unicode.ToUpper(u) != u {
			log.Fatalf("U+%04X uppercases to U+%04X, which isn't its own uppercase: folding wouldn't be idempotent", r, u)
		}
		fmt.Fprintf(&buf, "{0x%04X, 0x%04X},", r, u)
		n++
		if n%6 == 0 {
			buf.WriteString("\n")
		}
	}
	buf.WriteString("\n}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("upcase_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d mappings", n)
}
